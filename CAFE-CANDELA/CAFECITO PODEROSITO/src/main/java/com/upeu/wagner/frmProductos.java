    //Crear tabla si no existe
    private void crearTabla() {
        try (Statement stmt = conn.createStatement()) {
            stmt.execute("CREATE TABLE IF NOT EXISTS productos (" +
                    "id INTEGER PRIMARY KEY AUTOINCREMENT," +
                    "nombre TEXT NOT NULL," +
                    "descripcion TEXT NOT NULL," +
                    "precio TEXT NULL," +
                    "cantidad TEXT NULL," +
                    "codigo TEXT NULL)");
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al crear tabla: " + e.getMessage());
        }
    }
    
    //Cargar tabla
    private void cargarClientes() {
        modelo = new DefaultTableModel(new String[]{"ID", "Nombre","Descripción","Cantidad","Precio","Código"}, 0);
        tblproductos.setModel(modelo);
        modelo.setRowCount(0);
        try (Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery("SELECT * FROM productos")) {
            while (rs.next()) {
                modelo.addRow(new Object[]{
                        rs.getInt("id"),
                        rs.getString("nombre"),
                        rs.getString("descripcion"),
                        rs.getString("cantidad"),
                        rs.getString("precio"),
                        rs.getString("codigo")
                });
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al cargar clientes: " + e.getMessage());
        }
    }
    private String generarCodigoProducto() {
    String codigo = "P001";
    String sql = "SELECT codigo FROM productos ORDER BY id DESC LIMIT 1";
    try (Statement stmt = conn.createStatement(); ResultSet rs = stmt.executeQuery(sql)) {
        if (rs.next()) {
            String ultimo = rs.getString("codigo").substring(1); // Quita la P
            int num = Integer.parseInt(ultimo) + 1;
            codigo = String.format("P%03d", num); // Formato P001, P002...
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error al generar código: " + e.getMessage());
    }
    return codigo;
}

    
