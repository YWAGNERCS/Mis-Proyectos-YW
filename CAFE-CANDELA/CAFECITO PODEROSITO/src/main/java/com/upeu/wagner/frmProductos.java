    private void btnagregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnagregarActionPerformed
        String nombre=txtnombre.getText();
        String descripcion=txtdescripcion.getText();
        String cantidad=txtprecio.getText();
        String precio=txtcantidad.getText();
        String codigo = generarCodigoProducto();
        txtcodigo.setText(codigo);
        if (nombre.isEmpty() || cantidad.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Completa todos los campos.");
            return;
        }

        try (PreparedStatement ps = conn.prepareStatement("INSERT INTO productos(nombre,descripcion,precio,cantidad,codigo) VALUES(?,?,?,?,?)")) {
            ps.setString(1, nombre);
            ps.setString(2, descripcion);
            ps.setString(3, precio);
            ps.setString(4, cantidad);
            ps.setString(5, codigo);
            ps.executeUpdate();
            cargarClientes();
            limpiarCampos();
            txtnombre.requestFocus();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al agregar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnagregarActionPerformed

    private void btneliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btneliminarActionPerformed
        if(tblproductos.getSelectedRowCount()==1){
            int fila=tblproductos.getSelectedRow();
            idSeleccionado = Integer.parseInt(modelo.getValueAt(fila, 0).toString());
            int confirm = JOptionPane.showConfirmDialog(this, "¿Eliminar este producto?", "Confirmar", JOptionPane.YES_NO_OPTION);
            if (confirm == JOptionPane.YES_OPTION) {
                try (PreparedStatement ps = conn.prepareStatement("DELETE FROM productos WHERE id = ?")) {
                    ps.setInt(1, idSeleccionado);
                    ps.executeUpdate();
                    //limpiarCampos();
                    cargarClientes();
                } catch (SQLException e) {
                    JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
                }
            }
        }else{
            if(tblproductos.getRowCount()==0){
                JOptionPane.showMessageDialog(null, "La tabla esta vacia");
            }else{
                JOptionPane.showMessageDialog(null, "Seleccione solo una columna");
            }
        }
    }//GEN-LAST:event_btneliminarActionPerformed

    private void btnactualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnactualizarActionPerformed
        if (idSeleccionado == -1) return;
        String nombre = txtnombre.getText();
        String descripcion = txtdescripcion.getText();
        String precio = txtprecio.getText();
        String cantidad = txtcantidad.getText();
        String codigo = txtcodigo.getText();
        if (nombre.isEmpty() || precio.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Completa todos los campos.");
            return;
        }

        try (PreparedStatement ps = conn.prepareStatement("UPDATE productos SET nombre=?,descripcion=?,precio=?,cantidad=?,codigo=? WHERE id = ?")) {
            ps.setString(1, nombre);
            ps.setString(2, descripcion);
            ps.setString(3, precio);
            ps.setString(4, cantidad);
            ps.setString(5, codigo);
            ps.setInt(6, idSeleccionado);
            ps.executeUpdate();
            limpiarCampos();
            cargarClientes();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al actualizar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnactualizarActionPerformed

